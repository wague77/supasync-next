      out += `            foreignKeyName: "fk_${table.name}_${r.sourceColumn}";\n`;
      out += `            columns: ["${r.sourceColumn}"];\n`;
      out += `            referencedRelation: "${r.targetTable}";\n`;
      out += `            referencedColumns: ["${r.targetColumn}"];\n`;
      out += `          },\n`;
