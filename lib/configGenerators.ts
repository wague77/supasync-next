function mapToTSType(col: TableColumn, forInsert: boolean): string {
  const t = col.type.toLowerCase();
  let base = 'string';
  if (t === 'uuid' || t === 'text' || t.startsWith('varchar') || t === 'char') base = 'string';
  else if (t === 'boolean' || t === 'bool') base = 'boolean';
  else if (t.includes('int') || t === 'serial' || t === 'float' || t === 'numeric') base = 'number';
  else if (t.includes('json')) base = 'Json';
  else if (t.includes('vector')) base = 'number[]';
  else if (t.includes('date') || t.includes('time')) base = 'string';

  if (!forInsert && col.isNullable) {
    return `${base} | null`;
  }
  return base;
}

export function generateSqlDDL(result: DatabaseIntrospectionResult): string {
  let out = `-- ========================================================
-- SupaSync - Script de Définition & Configuration de Base
-- Projet: ${result.projectInfo.name || result.projectInfo.url}
-- Date: ${new Date().toISOString()}
-- ========================================================

-- Extensions PostgreSQL recommandées
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";
`;

  if (result.tables.some(t => t.columns.some(c => c.type.includes('vector')))) {
    out += `CREATE EXTENSION IF NOT EXISTS "vector";\n`;
  }

  out += `\n`;

  // Create tables
  result.tables.forEach(table => {
    out += `-- --------------------------------------------------------\n`;
    out += `-- Table: ${table.name}\n`;
    out += `-- --------------------------------------------------------\n`;
    out += `CREATE TABLE IF NOT EXISTS public.${table.name} (\n`;

    const colsSql = table.columns.map(col => {
      let s = `  ${col.name} ${col.type.toUpperCase()}`;
      if (col.isPrimary) s += ` PRIMARY KEY`;
      if (!col.isNullable && !col.isPrimary) s += ` NOT NULL`;
      if (col.defaultValue) s += ` DEFAULT ${col.defaultValue}`;
      return s;
    });

    out += colsSql.join(',\n');
    out += `\n);\n\n`;

    // Foreign keys
    table.columns
      .filter(c => c.foreignKey)
      .forEach(c => {
        const fk = c.foreignKey!;
        out += `ALTER TABLE public.${table.name} \n`;
        out += `  DROP CONSTRAINT IF EXISTS fk_${table.name}_${c.name},\n`;
        out += `  ADD CONSTRAINT fk_${table.name}_${c.name} \n`;
        out += `  FOREIGN KEY (${c.name}) REFERENCES public.${fk.targetTable}(${fk.targetColumn})`;
        if (fk.onDelete) out += ` ON DELETE ${fk.onDelete}`;
        out += `;\n\n`;
      });

    // RLS Activation
    out += `-- Activation de Row Level Security (RLS)\n`;
    out += `ALTER TABLE public.${table.name} ENABLE ROW LEVEL SECURITY;\n\n`;

    // Policies
    if (table.policies && table.policies.length > 0) {
      table.policies.forEach(p => {
        out += `CREATE POLICY "${p.name}" ON public.${table.name}\n`;
        out += `  FOR ${p.command} TO ${p.roles.join(', ')}\n`;
        if (p.definition) out += `  USING (${p.definition})\n`;
        if (p.check) out += `  WITH CHECK (${p.check})\n`;
        out += `;\n\n`;
      });
    } else {
      // Default safe policy template
      out += `-- Stratégie de sécurité par défaut pour ${table.name}\n`;
      out += `CREATE POLICY "Authenticated users can select ${table.name}" \n`;
      out += `  ON public.${table.name} FOR SELECT TO authenticated USING (true);\n\n`;
    }
  });

  // Recommended indexes
  out += `-- ========================================================\n`;
  out += `-- Index de Performance pour Clés Étrangères\n`;
  out += `-- ========================================================\n`;
  result.relationships.forEach(rel => {
    out += `CREATE INDEX IF NOT EXISTS idx_${rel.sourceTable}_${rel.sourceColumn} \n`;
    out += `  ON public.${rel.sourceTable}(${rel.sourceColumn});\n\n`;
  });

  return out;
}

export function generateSqlRLSHardening(result: DatabaseIntrospectionResult): string {
  let out = `-- ========================================================\n`;
  out += `-- Audit & Durcissement Sécurité RLS pour Supabase\n`;
  out += `-- Généré automatiquement par SupaSync\n`;
  out += `-- Score de sécurité actuel: ${result.securityAudit.score}/100\n`;
  out += `-- ========================================================\n\n`;

  result.tables.forEach(table => {
    out += `-- 1. Forcer RLS sur ${table.name}\n`;
    out += `ALTER TABLE public.${table.name} ENABLE ROW LEVEL SECURITY;\n`;

    const hasUserId = table.columns.some(c => c.name === 'user_id' || c.name === 'author_id');
    const isPublicLookup = ['categories', 'products', 'articles', 'plans'].includes(table.name);

    if (hasUserId) {
      const userCol = table.columns.find(c => c.name === 'user_id' || c.name === 'author_id')!.name;
      out += `CREATE POLICY "Users can only read own rows on ${table.name}"\n`;
      out += `  ON public.${table.name} FOR SELECT TO authenticated\n`;
      out += `  USING (auth.uid() = ${userCol});\n\n`;

      out += `CREATE POLICY "Users can insert own rows on ${table.name}"\n`;
      out += `  ON public.${table.name} FOR INSERT TO authenticated\n`;
      out += `  WITH CHECK (auth.uid() = ${userCol});\n\n`;

      out += `CREATE POLICY "Users can update own rows on ${table.name}"\n`;
      out += `  ON public.${table.name} FOR UPDATE TO authenticated\n`;
      out += `  USING (auth.uid() = ${userCol});\n\n`;
    } else if (isPublicLookup) {
      out += `CREATE POLICY "Public read for ${table.name}"\n`;
      out += `  ON public.${table.name} FOR SELECT TO anon, authenticated\n`;
      out += `  USING (true);\n\n`;
    } else {
      out += `CREATE POLICY "Authenticated users can read ${table.name}"\n`;
      out += `  ON public.${table.name} FOR SELECT TO authenticated\n`;
      out += `  USING (true);\n\n`;
    }
  });

  return out;
}

export function generateSeedScript(result: DatabaseIntrospectionResult, format: 'sql' | 'typescript'): string {
  if (format === 'sql') {
    let out = `-- Supabase Mock Seed Data\n-- Generated by SupaSync\n\n`;
    result.tables.forEach(table => {
      if (table.sampleRows && table.sampleRows.length > 0) {
        out += `-- Insert mock records into ${table.name}\n`;
        table.sampleRows.forEach(row => {
          const keys = Object.keys(row);
          const vals = keys.map(k => {
            const v = row[k];
            if (v === null) return 'NULL';
            if (typeof v === 'boolean') return v ? 'true' : 'false';
            if (typeof v === 'number') return v;
            return `'${String(v).replace(/'/g, "''")}'`;
          });
          out += `INSERT INTO public.${table.name} (${keys.join(', ')}) VALUES (${vals.join(', ')}) ON CONFLICT DO NOTHING;\n`;
        });
        out += `\n`;
      }
    });
    return out;
  }

  // TypeScript Seed script
  let out = `import { createClient } from '@supabase/supabase-js';
import type { Database } from './types/database.types';

const supabase = createClient<Database>(
  process.env.SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY! // Bypass RLS for seeding
);

export async function seedDatabase() {
  console.log('🌱 Seeding database...');\n`;

  result.tables.forEach(table => {
    if (table.sampleRows && table.sampleRows.length > 0) {
      out += `  // Seed ${table.name}\n`;
      out += `  await supabase.from('${table.name}').upsert(${JSON.stringify(table.sampleRows, null, 2)});\n\n`;
    }
  });

  out += `  console.log('✅ Database seeded successfully!');
}

if (import.meta.url === \`file://\${process.argv[1]}\`) {
  seedDatabase().catch(console.error);
}\n`;

  return out;
}

